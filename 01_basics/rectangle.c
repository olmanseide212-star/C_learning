#include <stdio.h>

int main() {
    int n, m;
    // 同时读取 n 和 m
    scanf("%d %d", &n, &m);
    
    // 【外层循环】：控制行数（一共画 n 行）
    for (int i = 0; i < n; i++) {
        
        // 【内层循环】：控制列数（每行画 m 个字符）
        for (int j = 0; j < m; j++) {
            // 核心判断：这个点是不是在矩形的“外边框”上？
            // 第一行(i==0)、最后一行(i==n-1)、第一列(j==0)、最后一列(j==m-1)
            if (i == 0 || i == n - 1 || j == 0 || j == m - 1) {
                printf("*");
            } else {
                printf(" "); // 如果不在边框上，就打印一个空格把中间掏空
            }
        }
        
        // 当这一行的 m 个字符全部画完后，才敲一次回车
        printf("\n");
    }
    
    return 0;
}
