#include <stdio.h>

int main() {
    // 【第一部分：基础算术运算】
    int a;
    int b;
    printf("请输入数字:");
    scanf("%d", &a);
    printf("请输入数字:");
    scanf("%d", &b);


    
    printf("--- 基础运算 ---\n");
    printf("加法: %d + %d = %d\n", a, b, a + b);
    printf("减法: %d - %d = %d\n", a, b, a - b);
    printf("乘法: %d * %d = %d\n", a, b, a * b);
    
    // 【第二部分：极其容易踩坑的“除法”】
    printf("\n--- 危险的除法 ---\n");
    // ⚠️ 警告：在C语言中，两个整数相除，结果一定会强制砍掉小数部分，只保留整数！
    printf("整数除法: %d / %d = %d\n", a, b, a / b);
    
    // 如果你想得到精确的小数，必须把其中一个数字临时“伪装”成小数（也就是浮点数 float）
    // 这个操作在编程里叫作“强制类型转换”
    printf("精确除法: %d.0 / %d = %f\n", a, b, (float)a / b);

    // 【第三部分：ACM中极其重要的“取模”运算】
    printf("\n--- 神奇的取模 (%%) ---\n");
    // ⚠️ 注意：% 符号在C语言里不是百分号，而是“求余数”！
    // 比如 10 除以 3，商是 3，余数是 1。所以 10 % 3 的结果就是 1。
    // 在打印时，因为 % 本身是特殊符号（像 %d ），所以要连续打两个 %% 才能在屏幕上显示出一个 %。
    printf("%d %% %d 的余数是: %d\n", a, b, a % b);
      
    // 小测试：你可以试着猜猜 10 % 2 的结果是多少？(可以用来判断奇偶数)

    return 0;
}
 