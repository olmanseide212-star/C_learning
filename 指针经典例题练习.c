/* ============================================================================
 * 例题 3：手写 strlen（指针遍历字符串）
 * ============================================================================
 * 【题目】：
 *   不使用 string.h，写函数 int my_strlen(char *s)，
 *   计算字符串 s 的长度（不含末尾 '\0'）。
 *   输入："Hello"  输出：5
 *   输入："ACM"    输出：3
 *
 * 【考点】：
 *   char* 指针对字符串的遍历；'\0' 是字符串的终止哨兵；
 *   两个指针相减 = 元素个数。
 *
 * 【思路】：
 *   让指针 p 从 s 的起点出发，不断 p++ 向前走，
 *   直到 *p == '\0' 停下来。
 *   此时 p 指向终止符，s 指向首字符，
 *   p - s 就是字符数量。
 *
 *   对比下标法（同样原理，两种写法都要会）：
 *     int i = 0;
 *     while (s[i] != '\0') i++;
 *     return i;
 * ============================================================================
 */

int my_strlen(char *s) {
    char *p = s;
    while (*p != '\0') p++;
    return p - s;   // 末尾地址 - 首地址 = 字符个数
}

