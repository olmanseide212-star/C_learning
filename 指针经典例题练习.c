/* ============================================================================
 * 例题 2：同时求数组的最大值与最小值
 * ============================================================================
 * 【题目】：
 *   写函数 void find_max_min(int *arr, int n, int *max_out, int *min_out)，
 *   读入 n 个整数，通过指针参数同时输出最大值和最小值。
 *   输入：5 个数 3 7 1 9 4
 *   输出：最大值=9  最小值=1
 *
 * 【考点】：
 *   C 函数只能 return 一个值；用指针参数当"输出槽"返回多个结果。
 *
 * 【思路】：
 *   先把 max_out 和 min_out 都指向首元素值，
 *   然后从第 2 个元素开始遍历：
 *     如果 arr[i] > *max_out → 更新 *max_out
 *     如果 arr[i] < *min_out → 更新 *min_out
 * ============================================================================
 */

void find_max_min(int *arr, int n, int *max_out, int *min_out) {
    *max_out = arr[0];
    *min_out = arr[0];
    for (int i = 1; i < n; i++) {
        if (arr[i] > *max_out) *max_out = arr[i];
        if (arr[i] < *min_out) *min_out = arr[i];
    }
}

