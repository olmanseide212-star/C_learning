/* ============================================================================
 * 例题 1：交换两个整数（指针传参）
 * ============================================================================
 * 【题目】：
 *   写一个函数 swap(int *a, int *b)，交换 a 和 b 所指向的两个整数的值。
 *   在 main 里验证：x=3, y=7 交换后 x=7, y=3。
 *
 * 【考点】：
 *   函数传值 vs 传址；解引用 *p 修改原变量。
 *
 * 【思路】：
 *   普通函数传值只是修改"替身"，外界无感知。
 *   传地址（int *a）后，*a 就是在直接操作原变量的内存，
 *   所以用第三个临时变量 temp 周转即可完成真正的交换。
 *
 *   伪代码：
 *     temp = *a       把 a 所指的值取出暂存
 *     *a   = *b       把 b 的值写入 a 的地址
 *     *b   = temp     把暂存值写入 b 的地址
 * ============================================================================
 */

void swap(int *a, int *b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

