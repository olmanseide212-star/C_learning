/* ============================================================================
 * 例题 5：指针版选择排序
 * ============================================================================
 * 【题目】：
 *   写函数 void selection_sort(int *arr, int n)，对数组升序排序。
 *   输入：5  →  3 1 4 1 5
 *   输出：1 1 3 4 5
 *
 * 【考点】：
 *   用指针替代下标操作数组；选择排序的思路。
 *
 * 【思路】：
 *   选择排序 = 每轮从"未排序区"找最小值，换到未排序区最前面。
 *
 *   外层指针 i 从头走到倒数第二个：
 *     min_p = i           先假设 i 是这轮最小的
 *     内层指针 j 从 i+1 扫到末尾：
 *       如果 *j < *min_p → 更新 min_p = j
 *     扫完后，swap(i, min_p) 把最小值放到正确位置
 * ============================================================================
 */

void selection_sort(int *arr, int n) {
    for (int *i = arr; i < arr + n - 1; i++) {
        int *min_p = i;                        // 先假设当前位置最小
        for (int *j = i + 1; j < arr + n; j++) {
            if (*j < *min_p) min_p = j;        // 找到更小的就记录指针
        }
        if (min_p != i) swap(i, min_p);        // 把最小值换到 i 的位置
    }
}

