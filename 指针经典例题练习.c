/* ============================================================================
 * 例题 4：数组翻转（双指针）
 * ============================================================================
 * 【题目】：
 *   写函数 void reverse(int *arr, int n)，原地翻转数组。
 *   输入：5  →  1 2 3 4 5
 *   输出：5 4 3 2 1
 *
 * 【考点】：
 *   左右双指针向中间夹逼；数组作为形参时传递的是首地址（真身降临）。
 *
 * 【思路】：
 *   left 指针从第 0 个出发，right 指针从最后一个出发，
 *   每轮把两端的值 swap，然后 left++, right--，
 *   直到 left >= right 停下。
 *
 *          1  2  3  4  5
 *          ^           ^
 *        left        right
 *   第1轮：swap(1,5) → 5 2 3 4 1，left=1, right=3
 *   第2轮：swap(2,4) → 5 4 3 2 1，left=2, right=2
 *   left >= right，结束！
 * ============================================================================
 */

void reverse(int *arr, int n) {
    int *left = arr;
    int *right = arr + n - 1;
    while (left < right) {
        swap(left, right);  // 复用例题1的 swap！
        left++;
        right--;
    }
}

