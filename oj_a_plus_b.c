#include <stdio.h>

int main() {
    int T;
    // 1. 先读取一共要测试多少组数据
    scanf("%d", &T);
    
    // 2. 这是一个“循环”结构，意思是只要 T 大于 0，大括号里的代码就会一直重复执行
    while (T > 0) {
        
        // 🚨 陷阱 1：数据范围爆炸！
        // 题目说 a 和 b 可能会接近 2的31次方（大约 21 亿）。
        // 如果把两个 21 亿相加，就会突破 42 亿，这超过了普通 int 盒子（最大只能装 21 亿）的极限！
        // 所以这里必须向电脑申请“超大号纸箱”：long long
        long long a, b;
        
        // 🚨 陷阱 2：占位符也要变大！
        // 既然换了超大号纸箱，原来的 %d 就装不下了，必须换成匹配 long long 的 %lld
        scanf("%lld %lld", &a, &b);
        printf("%lld\n", a + b);
        
        // 每算完一组，任务数量减 1，直到 T 变成 0，循环结束
        T = T - 1; 
    }
    
    return 0;
}
