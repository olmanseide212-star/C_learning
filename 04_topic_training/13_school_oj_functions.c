/* ============================================================================
 * 题号：【C系列4.x】素数判断（大数据与埃氏筛法）
 * 
 * 【题目描述】
 * 输入 T 组数据，每行一个整数 n (1 <= n <= 1000000)。
 * 若为素数输出 "YES"，否则输出 "NO"。
 * 
 * 【Hint 核心秘密】：
 * 1. n <= 10^6，如果每来一个数都用普通的试除法 (i*i <= n)，当 T 很大时会严重超时 (TLE)！
 * 2. 必须用【埃拉托斯特尼筛法（埃氏筛）】：
 *    利用全局大数组，在程序一开始就先把 100 万以内的所有素数全“筛”出来打好表！
 *    后面查表速度是 O(1) 瞬间出结果！
 * ============================================================================
 */

// ============================================================================
// 【第 3 题：HZNU OJ 1971 cyn 素数判断（预处理篇）】
// 
// 💡 老师在 OJ 系统中预设的外部环境：
// int isPrime[1000011];  <- 全局打表数组（1 代表素数，0 代表非素数）
// void getprime();       <- 只需要你实现这个打表函数！
// ============================================================================

// 👉 核心函数：埃氏筛打表（提交给 OJ 的就是这个函数）
void getprime() {
    // 步骤 1：先把 2~1000000 全部初始标记为素数 (1)
    // 0 和 1 保持默认值 0（不是素数）
    for (int i = 2; i <= 1000000; i++) {
        isPrime[i] = 1;
    }

    // 步骤 2：埃拉托斯特尼筛法（把每个素数的所有倍数击落为 0）
    for (int i = 2; i <= 1000000; i++) {
        if (isPrime[i] == 1) {
            for (int j = 2 * i; j <= 1000000; j += i) {
                isPrime[j] = 0;
            }
        }
    }
}

