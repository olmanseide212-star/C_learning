#include <stdio.h>
// 🔨 武器库：判断一个数字 n 是不是素数
// 返回值：如果是素数返回 1，如果不是素数返回 0
int is_prime(int n) {
    // TODO: 请在这里实现素数判断逻辑
    if (n == 1) {
        return 0;
    }
    for (int i = 2;i < n;i ++){
        if (n % i == 0){
            return 0;
        }
    }
    return 1;
}

int main() {
    int n;
    // TODO: 读入偶数 n
    // TODO: 循环枚举 p，计算 q = n - p
    // TODO: 调用 is_prime(p) 和 is_prime(q) 打印满足条件的等式
    scanf("%d",&n);
    int q;
    for (int p = 2;p < n;p ++){
        q = n - p;
        if (is_prime(p) && is_prime(q)){
            printf("%d = %d + %d\n",n,p,q);
        }
    }
    return 0;
}
