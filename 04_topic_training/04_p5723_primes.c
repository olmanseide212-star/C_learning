/**
 * ============================================================================
 * 洛谷题号：P5723 【深基4.例13】质数口袋
 * 题目链接：https://www.luogu.com.cn/problem/P5723
 * 
 * 【考核核心】：for 循环、布尔标记法（令某某等于 1）、累加求和与截断
 * 
 * 【题目描述】
 * 小 A 有一个装质数的口袋。他从 2 开始，从小到大依次检查每一个自然数：
 * 1. 如果这个数是质数，就将它装入口袋；
 * 2. 口袋有个承重上限 L，装入的所有质数之和不能超过 L；
 * 3. 一旦某个质数装进去会导致总和超过 L，就不能装它，并且装质数的过程当场结束。
 * 
 * 请按顺序输出装入口袋的所有质数（每行一个），最后输出总共装了多少个质数。
 * 
 * 【输入格式】
 * 一行一个正整数 L (1 <= L <= 100000)。
 * 
 * 【输出格式】
 * 先按顺序输出装入口袋的每一个质数，每行一个；
 * 最后一行输出装入的质数总个数。
 * 
 * 【输入样例】
 * 100
 * 
 * 【输出样例】
 * 2
 * 3
 * 5
 * 7
 * 11
 * 13
 * 17
 * 19
 * 23
 * 9
 * (说明：装入了 9 个质数，总和为 2+3+5+7+11+13+17+19+23 = 100 <= 100)
 * ============================================================================
 */

#include <stdio.h>
int main () {
    int L;
    scanf("%d",&L);
    int sum = 0,count = 0;
    for (int i = 2;;i ++){
        int is_prime = 1;
        for (int j = 2;j < i;j ++){
            if (i % j == 0){
                is_prime = 0;break;
            }
        }
        if (is_prime){
            if (sum + i <= L){
                printf("%d\n",i);sum += i;count ++;
            }
            else{break;}
        }
    }
    printf("%d\n",count);
    return 0;
}

