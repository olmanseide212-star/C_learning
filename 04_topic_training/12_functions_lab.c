#include <stdio.h>

// ============================================================================
// 1. 经典验证：值传递的“草人替身”陷阱
// ============================================================================
void bad_swap(int a, int b) {
    int temp = a;
    a = b;
    b = temp;
    // 这里的 a 和 b 只是草人替身，函数一结束立刻被系统火化销毁！
}

// ============================================================================
// 2. 例题 1：素数判官 is_prime
// 利用提前 return 彻底干掉 flag 标记变量！
// ============================================================================
int is_prime(int n) {
    if (n < 2) return 0;
    for (int i = 2; i * i <= n; i++) {
        if (n % i == 0) return 0; // 抓到现行，直接 return 0 下班！
    }
    return 1; // 查了一圈没毛病，宣判是质数
}

// ============================================================================
// 3. 例题 2：欧几里得辗转相除法 gcd（最大公约数）
// 极致的一行流递归
// ============================================================================
int gcd(int a, int b) {
    return (b == 0) ? a : gcd(b, a % b);
}

// ============================================================================
// 4. 例题 3：数组传参特例 —— reverse（数组原地翻转）
// 数组作为参数传递的是首地址，在函数里修改会【真实改变】外界的真数组！
// ============================================================================
void reverse_array(int arr[], int n) {
    int left = 0, right = n - 1;
    while (left < right) {
        int temp = arr[left];
        arr[left] = arr[right];
        arr[right] = temp;
        left++;
        right--;
    }
}

// ============================================================================
// 5. 例题 4：斐波那契数列递归实现
// 递归两要素：终止条件（出口） + 规模缩小递推
// ============================================================================
long long fib(int n) {
    if (n == 1 || n == 2) return 1;
    return fib(n - 1) + fib(n - 2);
}


// ============================================================================
// 主函数：现场检验各个函数的威力
// ============================================================================
int main() {
    printf("========== 🧪 实验 1：草人替身（值传递）验证 ==========\n");
    int x = 3, y = 5;
    bad_swap(x, y);
    printf("调用 bad_swap(x, y) 后的结果: x = %d, y = %d (外界真身毫不知情！)\n\n", x, y);

    printf("========== 🧪 实验 2：素数判官 is_prime ==========\n");
    int test_num = 17;
    printf("%d 是素数吗？%s\n\n", test_num, is_prime(test_num) ? "【是真素数】" : "【不是素数】");

    printf("========== 🧪 实验 3：欧几里得最大公约数 gcd ==========\n");
    int a = 24, b = 36;
    printf("gcd(%d, %d) = %d\n\n", a, b, gcd(a, b));

    printf("========== 🧪 实验 4：数组真身传递 reverse_array ==========\n");
    int nums[5] = {10, 20, 30, 40, 50};
    printf("翻转前: ");
    for (int i = 0; i < 5; i++) printf("%d ", nums[i]);
    printf("\n");

    reverse_array(nums, 5); // 数组传入，真身被翻转！

    printf("翻转后: ");
    for (int i = 0; i < 5; i++) printf("%d ", nums[i]);
    printf(" (真身被真正改动了！)\n\n");

    printf("========== 🧪 实验 5：递归斐波那契 fib ==========\n");
    printf("第 10 个斐波那契数是: %lld\n", fib(10));

    return 0;
}
