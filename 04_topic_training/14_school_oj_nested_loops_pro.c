//  * 输入整数 n (1 <= n <= 9)，输出对称数字图形。
//  * 注意：每行最后一个数字后没有任何空格。
//  * 
//  * 【输入样例】
//  * 5
//  * 
//  * 【输出样例】
//  *     1
//  *    121
//  *   12321
//  *  1234321
//  * 123454321
//  *  1234321
//  *   12321
//  *    121
//  *     1
//  * ============================================================================
//  */
void solve_pro_1() {
    int n;
    while (scanf("%d", &n) != EOF) {
        // 1. 上半部分（包括中间最长的一行）
        // 💡 关键细节：题目要求每一行最前面都有 1 个基准空格，所以是 n - i + 1 个空格！
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n - i + 1; j++) printf(" ");
            for (int j = 1; j <= i; j++) printf("%d", j);
            for (int j = i - 1; j >= 1; j--) printf("%d", j);
            printf("\n");
        }
        // 2. 下半部分（i 从 n - 1 倒数到 1）
        for (int i = n - 1; i > 0; i--) {
            for (int j = 1; j <= n - i + 1; j++) printf(" ");
            for (int j = 1; j <= i; j++) printf("%d", j);
            for (int j = i - 1; j >= 1; j--) printf("%d", j);
            printf("\n");
        }
    }
}

