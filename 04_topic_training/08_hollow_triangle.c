/**
 * ============================================================================
 * 经典 ACM / HDU 2091 题：掏空三角形（空心等腰三角形）
 * 
 * 【题目描述】
 * wzj 非常擅长 UI 设计，被猎头公司招去掏三角形。
 * 给出各种花纹材料的字符和等腰三角形的高 n (0 < n < 41)，底边长为 2n - 1。
 * 如果遇到 '@' 字符，则表示输入结束。
 * 
 * 【输入格式】
 * 多组输入。每行包含一个字符和一个整数 n (0 < n < 41)。
 * 最后一行为单个 '@'，表示结束。
 * 
 * 【输出格式】
 * 1. 打印对应的空心等腰三角形；
 * 2. 每个样板三角形之间应【空上一行】（即除第一个外，每个输出前先换行）；
 * 3. 行末绝对不能有多余的空格；
 * 4. 三角形内部掏空。
 * 
 * 【输入样例】
 * X 2
 * A 7
 * @
 * 
 * 【输出样例】
 *  X
 * XXX
 * 
 *       A
 *      A A
 *     A   A
 *    A     A
 *   A       A
 *  A         A
 * AAAAAAAAAAAAA
 * ============================================================================
 */

#include <stdio.h>
int main() {
    char ch;
    int n,i,j;
    while(scanf(" %c",&ch) != EOF && ch != '@'){
        scanf("%d",&n);
        if (n == 1) printf ("%c\n",ch);
        else{
            for (i = 0;i < n-1;i ++){
                for (j = 1;j <= n + i;j ++){
                    printf("%c",j == n - i || j == n + i ? ch : ' ' );
                }
                printf("\n");
            }
            if (n > 1) {
                for (j = 0;j < 2 * n -1;j ++){
                    printf("%c",ch);
                }
                printf("\n");
            }
        }
        printf("\n");
    }
    return 0;
}


    
    