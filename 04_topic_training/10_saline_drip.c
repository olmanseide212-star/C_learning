/**
 * ============================================================================
 * 经典 ACM 模拟题：挂盐水
 * 
 * 【题目描述】
 * cjc 由于背单词太努力，生病去挂盐水。
 * 盐水总共 VUL 毫升，每一滴是 D 毫升。
 * 滴落规律：
 * 先滴 1 滴，停 1 秒；
 * 再滴 2 滴，停 1 秒；
 * 再滴 3 滴，停 1 秒...
 * 依次类推。
 * 每一滴速度是 1 秒（假设最后一滴不到 D 毫升，也算 1 秒）。
 * 停一下的时间也是 1 秒。
 * 问：这瓶水什么时候能挂完？
 * 
 * 【输入格式】
 * 多组输入。每行包含两个整数 VUL 和 D (0 < D, VUL < 5000)。
 * 
 * 【输出格式】
 * 每组数据输出一行，代表挂完盐水需要的总时间（秒）。
 * 
 * 【输入样例】
 * 10 1
 * 200 500
 * 123 5
 * 846 5
 * 11 2
 * 1212 5
 * 
 * 【输出样例】
 * 13
 * 1
 * 31
 * 187
 * 8
 * 264
 * 
 * 【💡 关键破案提醒】
 * 1. 向上取整算总滴数：不到 D 毫升也算一滴。公式：(VUL + D - 1) / D
 * 2. 拔针走人：最后一滴滴完立即结束，绝对不能再休息 1 秒！
 * ============================================================================
 */

#include <stdio.h>
int main() {
    int vul, d;
    while(scanf("%d %d",&vul,&d) != EOF){
        int time = 0,max_count = 1,count = 0;
        while (vul > 0){
            for (int i = 0; i < max_count;i ++){
                time++;vul -= d;
                if (vul <= 0) break;
            }
            if (vul > 0) {
                max_count ++;time ++;
            } 
        }
        printf("%d\n",time);
    }
    return 0;
}
