/**
 * ============================================================================
 * 洛谷题号：P5721 【深基4.例6】数字直角三角形
 * 题目链接：https://www.luogu.com.cn/problem/P5721
 * 
 * 【题目描述】
 * 给出正整数 n (1 <= n <= 13)，输出一个直角边长度为 n 的数字直角三角形。
 * 
 * 【格式要求】
 * 1. 所有数字必须是两位数输出，不足两位前面补 0 (使用 %02d)；
 * 2. 数字连续递增（从 01 开始，一直往后数）；
 * 3. 每一行的数字之间【没有空格】；
 * 4. 每一行结束后换行。
 * 
 * 【输入样例】
 * 5
 * 
 * 【输出样例】
 * 0102030405
 * 06070809
 * 101112
 * 1314
 * 15
 * ============================================================================
 */

#include <stdio.h>
int main() {
    int i,j,n,count = 1;
    scanf("%d",&n);
    for (i = n;i > 0;i --){
        for (j = i;j > 0;j--){
            printf("%02d",count);
            count ++;
        }
        printf("\n");
    }
    return 0;
}

