/* ============================================================================
 * 关卡 1：【洛谷 P1428】小鱼比可爱（数组前缀比较）
 * 链接：https://www.luogu.com.cn/problem/P1428
 * 
 * 【题目描述】
 * 给出 n (n <= 100) 条鱼的可爱值，每条鱼只能看到左边的鱼。
 * 问：每条鱼能看到多少条可爱值【严格小于自己】的鱼？
 * 
 * 【输入样例】
 * 6
 * 4 3 0 5 1 2
 * 
 * 【输出样例】
 * 0 0 0 3 1 2
 * 
 * 【思路提示】
 * 1. 开数组 a[105] 存下每条鱼的可爱值；
 * 2. 对第 i 条鱼，用内层循环 j 从 0 扫到 i - 1；
 * 3. 统计 a[j] < a[i] 的个数并打印。
 * ============================================================================
 */
void solve_p1428() {
    int n;
    scanf("%d",&n);
    int a[105];
    for (int i = 0;i < n ;i ++){
        scanf("%d",&a[i]);
    }
    for (int i = 0;i < n;i ++){
        int count = 0;
        for (int j = 0; j < i;j ++){
            if (a[j] < a[i]) count ++;
        }
        printf("%d ",count);
    }
    printf("\n");
}


/* ============================================================================
 * 关卡 2：【洛谷 P1047】校门外的树（数组标记法 / 区间模拟）
 * 链接：https://www.luogu.com.cn/problem/P1047
 * 
 * 【题目描述】
 * 马路长 L (1 <= L <= 10000)，上面种了 L+1 棵树（位置 0 到 L）。
 * 有 m 个区间 [u, v] 要修地铁移走树木。问最后剩下多少棵树？
 * 
 * 【输入样例】
 * 500 3
 * 150 300
 * 100 200
 * 470 471
 * 
 * 【输出样例】
 * 298
 * 
 * 【思路提示】
 * 1. 开数组 tree[10005]，初始全都为 1（表示有树）；
 * 2. 读入每个区间 [u, v]，循环将 tree[i] 置为 0（被移走）；
 * 3. 最终统计依然为 1 的树木总数。
 * ============================================================================
 */
void solve_p1047() {
    int L,m;
    scanf("%d %d",&L,&m);
    int tree[10005];
    for (int i = 0;i <= L;i ++){
        tree[i] = 1;
    }
    while(m --){
        int u,v;
        scanf("%d %d",&u,&v);
        for (int i = u;i <= v;i ++){
            tree[i] = 0;
        }
    }
    int count = 0;
    for (int i = 0;i <= L;i ++){
        if (tree[i] == 1) count++;
    }
    printf("%d",count);
}


