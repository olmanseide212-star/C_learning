/**
 * ============================================================================
 * 洛谷题号：P5725 【深基4.习8】求三角形
 * 题目链接：https://www.luogu.com.cn/problem/P5725
 * 
 * 【题目描述】
 * 输入一个正整数 n (1 <= n <= 9)。
 * 依次输出两个由数字组成的图形：
 * 1. 一个 n * n 的数字正方形（数字从 01 开始递增到 n*n）；
 * 2. 中间空一行；
 * 3. 一个直角边长为 n 的【右对齐】数字直角三角形（数字重新从 01 开始递增）。
 * 
 * 【格式要求】
 * 1. 所有数字必须占两位场宽，不足两位前面补 0 (使用 %02d)；
 * 2. 矩形与三角形之间【空一行】；
 * 3. 三角形是【靠右对齐】的，前面需要补空格对齐！
 * 
 * 【输入样例】
 * 4
 * 
 * 【输出样例】
 * 01020304
 * 05060708
 * 09101112
 * 13141516
 * 
 *       01
 *     0203
 *   040506
 * 07080910
 * 
 * 【💡 关键陷阱提示】
 * 注意看三角形第 1 行前面有多少个空格！
 * 因为每个数字占【2 个字符宽】(%02d)，所以缺 1 个数字，前面就需要补【2 个空格】！
 * ============================================================================
 */

#include <stdio.h>
int main() {
    int n,count = 1;
    scanf("%d",&n);
    for (int i = 1 ;i <= n;i ++){
        for (int j = 1 ;j <= n;j++){
            printf("%02d",count);
            count ++;
        }
        printf("\n");
    }
    printf("\n");count = 1;
    for (int i = n;i > 0;i --){
        for (int j = 1;j <= n;j++){
            if (j < i) printf("  ");
            else {
                printf("%02d",count);count ++;
            }
        }
        printf("\n");
    }
    return 0;
}




    